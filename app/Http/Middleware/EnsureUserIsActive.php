namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Symfony\Component\HttpFoundation\Response;

class EnsureUserIsActive
{
    /**
     * Encerra imediatamente a sessão de um usuário desativado.
     *
     * Sem esta verificação, desativar uma conta no painel não derrubava as
     * sessões já abertas: o usuário continuava navegando até sair sozinho.
     */
    public function handle(Request $request, Closure $next): Response
    {
        $user = $request->user();

        if ($user && ! $user->is_active) {
            Auth::logout();

            $request->session()->invalidate();
            $request->session()->regenerateToken();

            return redirect()
                ->route('login')
                ->with('error', 'Sua conta foi desativada. Procure o administrador do sistema.');
        }

        return $next($request);
    }
}
